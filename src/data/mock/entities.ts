/** Returns all entities for a given layer id. */
export function getEntitiesByLayer(layerId: LayerId): AnyMapEntity[] {
  return mockEntities.filter((e) => e.layerId === layerId);
}

/** Returns a single entity by its id, or undefined. */
export function getEntityById(id: string): AnyMapEntity | undefined {
  return mockEntities.find((e) => e.id === id);
}

